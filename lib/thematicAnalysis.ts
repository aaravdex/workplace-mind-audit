// ── Tone lexicon (a modest signal, not sentiment analysis) ────────────────────

const POSITIVE = ["good", "great", "love", "enjoy", "positive", "helpful", "supportive", "appreciate", "valued", "clear", "fair", "flexible"];
const NEGATIVE = ["too much", "unclear", "stress", "burnout", "exhausted", "unfair", "overwhelm", "confusing", "micromanage", "understaffed", "impossible", "pressure", "ignored", "blamed"];

// ── Thresholds ────────────────────────────────────────────────────────────────

/** Dataset must have at least this many comments before any verbatim shows. */
const MIN_VERBATIM_SAMPLE = 5;
/** A theme must itself carry at least this many comments before a verbatim shows. */
const MIN_THEME_FOR_QUOTE = 3;
/** Below this prevalence a candidate theme is flagged thin (a code, not a theme). */
const MIN_PREVALENCE_FOR_THEME = 3;

// ── Matching ──────────────────────────────────────────────────────────────────

const SINGLE_WORD = /^[a-z]+$/;

function toneOf(pos: number, neg: number): ThemeTone {
  if (neg > pos) return "negative";
  if (pos > neg) return "positive";
  return "mixed";
}

function matches(lowerText: string, keyword: string): boolean {
  if (SINGLE_WORD.test(keyword)) {
    // Word-boundary match to avoid "manage" catching "management".
    return new RegExp(`\\b${keyword}\\b`).test(lowerText);
  }
  return lowerText.includes(keyword);
}

// ── Public types ──────────────────────────────────────────────────────────────

export interface CodeResult {
  id: string;
  label: string;
  definition: string;
  candidateThemeId: string;
  count: number;
  segments: string[];
}

export type ThemeTone = "negative" | "mixed" | "positive";

export interface CandidateTheme {
  id: string;
  provisionalName: string;
  centralOrganisingConcept: string;
  /** Distinct comments coded to any constituent code. */
  prevalence: number;
  tone: ThemeTone;
  codes: CodeResult[];
  /** Prevalence broken down by segment (segments meeting no floor here — the
   *  report applies min-N suppression when rendering). */
  bySegment: { segment: string; count: number }[];
  /** Redacted illustrative extracts — only when gates pass; else empty. */
  illustrativeExtracts: string[];
  /** True when prevalence is too thin to stand as a theme on its own. */
  thin: boolean;
}

export interface Familiarisation {
  totalComments: number;
  respondentsWithText: number;
  byQuestion: { questionId: number; text: string; count: number }[];
  meanWordCount: number;
  /** Comments the codebook did not catch — flagged for manual reading. */
  uncodedCount: number;
}

export interface ThematicAnalysis {
  familiarisation: Familiarisation;
  codes: CodeResult[];
  candidateThemes: CandidateTheme[];
}

// ── Engine ────────────────────────────────────────────────────────────────────

const QUESTION_TEXT = new Map(OPEN_TEXT_QUESTIONS.map((q) => [q.id, q.text]));

/**
 * Run the deterministic first pass (Phases 1–3). Returns familiarisation
 * descriptives, code frequencies, and candidate themes with prevalence, tone,
 * per-segment breakdown and anonymity-gated extracts. Everything here is a
 * CANDIDATE for consultant review — never a finished interpretation.
 */
export function analyseOpenText(
  entries: OpenTextEntry[],
  opts: { reportingThreshold: number; allowVerbatims: boolean },
): ThematicAnalysis {
  const clean = entries
    .map((e) => ({ ...e, text: (e.text ?? "").trim() }))
    .filter((e) => e.text.length > 0);

  // ── Phase 2: coding ──
  interface CodeAcc {
    count: number;
    segments: Set<string>;
    themeComments: Set<number>;
    extracts: { text: string; len: number }[];
  }
  const codeAcc = new Map<string, CodeAcc>();
  const themeComments = new Map<string, Set<number>>();
  const themeTone = new Map<string, { pos: number; neg: number }>();
  const themeSegments = new Map<string, Map<string, number>>();
  const themeExtracts = new Map<string, { text: string; len: number }[]>();
  const codedComments = new Set<number>();

  clean.forEach((e, idx) => {
    const t = e.text.toLowerCase();
    const pos = POSITIVE.filter((w) => matches(t, w)).length;
    const neg = NEGATIVE.filter((w) => matches(t, w)).length;
    const redacted = redactOpenText(e.text);
    const themesHitThisComment = new Set<string>();

    for (const code of CODEBOOK) {
      if (!code.keywords.some((k) => matches(t, k))) continue;
      codedComments.add(idx);

      const acc =
        codeAcc.get(code.id) ??
        { count: 0, segments: new Set<string>(), themeComments: new Set<number>(), extracts: [] };
      acc.count += 1;
      if (e.segment) acc.segments.add(e.segment);
      codeAcc.set(code.id, acc);

      const ctId = code.candidateThemeId;
      if (!themeComments.has(ctId)) themeComments.set(ctId, new Set());
      themeComments.get(ctId)!.add(idx);

      if (!themesHitThisComment.has(ctId)) {
        themesHitThisComment.add(ctId);
        const tone = themeTone.get(ctId) ?? { pos: 0, neg: 0 };
        tone.pos += pos;
        tone.neg += neg;
        themeTone.set(ctId, tone);

        if (e.segment) {
          const seg = themeSegments.get(ctId) ?? new Map<string, number>();
          seg.set(e.segment, (seg.get(e.segment) ?? 0) + 1);
          themeSegments.set(ctId, seg);
        }

        const ex = themeExtracts.get(ctId) ?? [];
        if (redacted.length <= 160) ex.push({ text: redacted, len: redacted.length });
        themeExtracts.set(ctId, ex);
      }
    }
  });

  // ── Phase 1: familiarisation ──
  const byQuestion = new Map<number, number>();
  let wordTotal = 0;
  const respondents = new Set<number>();
  clean.forEach((e, idx) => {
    respondents.add(idx);
    wordTotal += e.text.split(/\s+/).filter(Boolean).length;
    if (e.questionId != null) byQuestion.set(e.questionId, (byQuestion.get(e.questionId) ?? 0) + 1);
  });

  const familiarisation: Familiarisation = {
    totalComments: clean.length,
    respondentsWithText: respondents.size,
    byQuestion: [...byQuestion.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([questionId, count]) => ({
        questionId,
        text: QUESTION_TEXT.get(questionId) ?? `Question ${questionId}`,
        count,
      })),
    meanWordCount: clean.length ? Math.round(wordTotal / clean.length) : 0,
    uncodedCount: clean.length - codedComments.size,
  };

  // ── Assemble codes ──
  const codes: CodeResult[] = CODEBOOK.map((c) => {
    const acc = codeAcc.get(c.id);
    return {
      id: c.id,
      label: c.label,
      definition: c.definition,
      candidateThemeId: c.candidateThemeId,
      count: acc?.count ?? 0,
      segments: acc ? [...acc.segments].sort() : [],
    };
  })
    .filter((c) => c.count > 0)
    .sort((a, b) => b.count - a.count || a.id.localeCompare(b.id));

  const codesByTheme = new Map<string, CodeResult[]>();
  for (const c of codes) {
    if (!codesByTheme.has(c.candidateThemeId)) codesByTheme.set(c.candidateThemeId, []);
    codesByTheme.get(c.candidateThemeId)!.push(c);
  }

  // ── Phase 3: candidate themes ──
  const datasetAllowsQuotes =
    opts.allowVerbatims && clean.length >= Math.max(opts.reportingThreshold, MIN_VERBATIM_SAMPLE);

  const candidateThemes: CandidateTheme[] = CANDIDATE_THEMES.map((spec) => {
    const prevalence = themeComments.get(spec.id)?.size ?? 0;
    const tone = themeTone.get(spec.id) ?? { pos: 0, neg: 0 };
    const bySegment = [...(themeSegments.get(spec.id) ?? new Map<string, number>())]
      .map(([segment, count]) => ({ segment, count }))
      .sort((a, b) => b.count - a.count || a.segment.localeCompare(b.segment));

    const showQuotes = datasetAllowsQuotes && prevalence >= MIN_THEME_FOR_QUOTE;
    const illustrativeExtracts = showQuotes
      ? (themeExtracts.get(spec.id) ?? [])
          .sort((a, b) => a.len - b.len || a.text.localeCompare(b.text))
          .slice(0, 2)
          .map((x) => x.text)
      : [];

    return {
      id: spec.id,
      provisionalName: spec.provisionalName,
      centralOrganisingConcept: spec.centralOrganisingConcept,
      prevalence,
      tone: toneOf(tone.pos, tone.neg),
      codes: codesByTheme.get(spec.id) ?? [],
      bySegment,
      illustrativeExtracts,
      thin: prevalence > 0 && prevalence < MIN_PREVALENCE_FOR_THEME,
    };
  })
    .filter((t) => t.prevalence > 0)
    .sort((a, b) => b.prevalence - a.prevalence || a.id.localeCompare(b.id));

  return { familiarisation, codes, candidateThemes };
}

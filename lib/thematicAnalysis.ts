// ── Tone lexicon (a modest signal, not sentiment analysis) ────────────────────

const POSITIVE = ["good", "great", "love", "enjoy", "positive", "helpful", "supportive", "appreciate", "valued", "clear", "fair", "flexible"];
const NEGATIVE = ["too much", "unclear", "stress", "burnout", "exhausted", "unfair", "overwhelm", "confusing", "micromanage", "understaffed", "impossible", "pressure", "ignored", "blamed"];

// ── Thresholds ────────────────────────────────────────────────────────────────

/** Dataset must have at least this many comments before any verbatim shows. */
const MIN_VERBATIM_SAMPLE = 5;
/** A theme must itself carry at least this many comments before a verbatim shows. */
const MIN_THEME_FOR_QUOTE = 3;
/** Below this prevalence a candidate theme is flagged thin (a code, not a theme). */
const MIN_PREVALENCE_FOR_THEME = 3;

// ── Matching ──────────────────────────────────────────────────────────────────

const SINGLE_WORD = /^[a-z]+$/;

function toneOf(pos: number, neg: number): ThemeTone {
  if (neg > pos) return "negative";
  if (pos > neg) return "positive";
  return "mixed";
}

function matches(lowerText: string, keyword: string): boolean {
  if (SINGLE_WORD.test(keyword)) {
    // Word-boundary match to avoid "manage" catching "management".
    return new RegExp(`\\b${keyword}\\b`).test(lowerText);
  }
  return lowerText.includes(keyword);
}

// ── Consultant review vocabulary (Phases 4–5) ─────────────────────────────────

export type ThemeDecision = "unreviewed" | "keep" | "merge" | "discard";

export const THEME_DECISION_LABEL: Record<ThemeDecision, string> = {
  unreviewed: "Candidate — not yet reviewed",
  keep: "Confirmed theme",
  merge: "Merged into another theme",
  discard: "Discarded (not a theme)",
};

export interface ThemeReviewEntry {
  decision: ThemeDecision;
  /** Phase 5: consultant's final theme name. */
  name?: string;
  /** Phase 5: consultant's theme definition. */
  definition?: string;
  /** Phase 4: reviewing rationale. */
  note?: string;
  /** When decision === "merge": the candidate theme id this folds into. */
  mergedInto?: string;
}

/** Keyed by candidate theme id. Stored as audit_annotations.theme_review. */
export type ThemeReview = Record<string, ThemeReviewEntry>;

// ── Public types ──────────────────────────────────────────────────────────────

export interface CodeResult {
  id: string;
  label: string;
  definition: string;
  candidateThemeId: string;
  count: number;
  segments: string[];
}

export type ThemeTone = "negative" | "mixed" | "positive";

export interface CandidateTheme {
  id: string;
  provisionalName: string;
  centralOrganisingConcept: string;
  /** Distinct comments coded to any constituent code. */
  prevalence: number;
  tone: ThemeTone;
  codes: CodeResult[];
  /** Prevalence broken down by segment (the report applies min-N suppression). */
  bySegment: { segment: string; count: number }[];
  /** Redacted illustrative extracts — only when gates pass; else empty. */
  illustrativeExtracts: string[];
  /** True when prevalence is too thin to stand as a theme on its own. */
  thin: boolean;
}

/** A candidate theme after the consultant's Phase 4–5 review is applied. */
export interface ReviewedTheme {
  id: string;
  /** Consultant name if given (Phase 5), else the provisional name. */
  name: string;
  /** Consultant definition if given (Phase 5), else the central organising concept. */
  definition: string;
  /** "confirmed" once a consultant keeps or names it; otherwise still a candidate. */
  status: "confirmed" | "candidate";
  reviewed: boolean;
  prevalence: number;
  tone: ThemeTone;
  codes: CodeResult[];
  bySegment: { segment: string; count: number }[];
  illustrativeExtracts: string[];
  thin: boolean;
  /** Provisional names of any candidate themes merged into this one. */
  mergedFrom: string[];
  note?: string;
}

export interface Familiarisation {
  totalComments: number;
  respondentsWithText: number;
  byQuestion: { questionId: number; text: string; count: number }[];
  meanWordCount: number;
  /** Comments the codebook did not catch — flagged for manual reading. */
  uncodedCount: number;
}

export interface ThematicAnalysis {
  familiarisation: Familiarisation;
  codes: CodeResult[];
  candidateThemes: CandidateTheme[];
  /** Candidate themes with the consultant review applied (Phases 4–5). With no
   *  review supplied, every theme is an unreviewed candidate. */
  reviewedThemes: ReviewedTheme[];
}

// ── Engine ────────────────────────────────────────────────────────────────────

const QUESTION_TEXT = new Map(OPEN_TEXT_QUESTIONS.map((q) => [q.id, q.text]));

/**
 * Run the deterministic first pass (Phases 1–3) and apply the consultant review
 * (Phases 4–5, when supplied). Everything the machine produces is a CANDIDATE;
 * the reviewed layer reflects human decisions applied deterministically.
 */
export function analyseOpenText(
  entries: OpenTextEntry[],
  opts: { reportingThreshold: number; allowVerbatims: boolean; review?: ThemeReview },
): ThematicAnalysis {
  const clean = entries
    .map((e) => ({ ...e, text: (e.text ?? "").trim() }))
    .filter((e) => e.text.length > 0);

  // ── Phase 2: coding ──
  const codeAcc = new Map<string, { count: number; segments: Set<string> }>();
  const themeComments = new Map<string, Set<number>>();
  const themeSegmentComments = new Map<string, Map<string, Set<number>>>();
  const themeTone = new Map<string, { pos: number; neg: number }>();
  const themeExtracts = new Map<string, { text: string; len: number }[]>();
  const codedComments = new Set<number>();

  clean.forEach((e, idx) => {
    const t = e.text.toLowerCase();
    const pos = POSITIVE.filter((w) => matches(t, w)).length;
    const neg = NEGATIVE.filter((w) => matches(t, w)).length;
    const redacted = redactOpenText(e.text);
    const themesHitThisComment = new Set<string>();

    for (const code of CODEBOOK) {
      if (!code.keywords.some((k) => matches(t, k))) continue;
      codedComments.add(idx);

      const acc = codeAcc.get(code.id) ?? { count: 0, segments: new Set<string>() };
      acc.count += 1;
      if (e.segment) acc.segments.add(e.segment);
      codeAcc.set(code.id, acc);

      const ctId = code.candidateThemeId;
      if (!themeComments.has(ctId)) themeComments.set(ctId, new Set());
      themeComments.get(ctId)!.add(idx);

      if (!themesHitThisComment.has(ctId)) {
        themesHitThisComment.add(ctId);
        const tone = themeTone.get(ctId) ?? { pos: 0, neg: 0 };
        tone.pos += pos;
        tone.neg += neg;
        themeTone.set(ctId, tone);

        if (e.segment) {
          const seg = themeSegmentComments.get(ctId) ?? new Map<string, Set<number>>();
          if (!seg.has(e.segment)) seg.set(e.segment, new Set());
          seg.get(e.segment)!.add(idx);
          themeSegmentComments.set(ctId, seg);
        }

        const ex = themeExtracts.get(ctId) ?? [];
        if (redacted.length <= 160) ex.push({ text: redacted, len: redacted.length });
        themeExtracts.set(ctId, ex);
      }
    }
  });

  // ── Phase 1: familiarisation ──
  const byQuestion = new Map<number, number>();
  let wordTotal = 0;
  const respondents = new Set<number>();
  clean.forEach((e, idx) => {
    respondents.add(idx);
    wordTotal += e.text.split(/\s+/).filter(Boolean).length;
    if (e.questionId != null) byQuestion.set(e.questionId, (byQuestion.get(e.questionId) ?? 0) + 1);
  });

  const familiarisation: Familiarisation = {
    totalComments: clean.length,
    respondentsWithText: respondents.size,
    byQuestion: [...byQuestion.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([questionId, count]) => ({
        questionId,
        text: QUESTION_TEXT.get(questionId) ?? `Question ${questionId}`,
        count,
      })),
    meanWordCount: clean.length ? Math.round(wordTotal / clean.length) : 0,
    uncodedCount: clean.length - codedComments.size,
  };

  // ── Assemble codes ──
  const codes: CodeResult[] = CODEBOOK.map((c) => {
    const acc = codeAcc.get(c.id);
    return {
      id: c.id,
      label: c.label,
      definition: c.definition,
      candidateThemeId: c.candidateThemeId,
      count: acc?.count ?? 0,
      segments: acc ? [...acc.segments].sort() : [],
    };
  })
    .filter((c) => c.count > 0)
    .sort((a, b) => b.count - a.count || a.id.localeCompare(b.id));

  const codesByTheme = new Map<string, CodeResult[]>();
  for (const c of codes) {
    if (!codesByTheme.has(c.candidateThemeId)) codesByTheme.set(c.candidateThemeId, []);
    codesByTheme.get(c.candidateThemeId)!.push(c);
  }

  const segmentBreakdown = (id: string) =>
    [...(themeSegmentComments.get(id) ?? new Map<string, Set<number>>())]
      .map(([segment, set]) => ({ segment, count: set.size }))
      .sort((a, b) => b.count - a.count || a.segment.localeCompare(b.segment));

  const datasetAllowsQuotes =
    opts.allowVerbatims && clean.length >= Math.max(opts.reportingThreshold, MIN_VERBATIM_SAMPLE);

  const extractsFor = (candidates: { text: string; len: number }[], prevalence: number) =>
    datasetAllowsQuotes && prevalence >= MIN_THEME_FOR_QUOTE
      ? candidates
          .sort((a, b) => a.len - b.len || a.text.localeCompare(b.text))
          .slice(0, 2)
          .map((x) => x.text)
      : [];

  // ── Phase 3: candidate themes ──
  const specById = new Map(CANDIDATE_THEMES.map((s) => [s.id, s]));
  const candidateThemes: CandidateTheme[] = CANDIDATE_THEMES.map((spec) => {
    const prevalence = themeComments.get(spec.id)?.size ?? 0;
    const tone = themeTone.get(spec.id) ?? { pos: 0, neg: 0 };
    return {
      id: spec.id,
      provisionalName: spec.provisionalName,
      centralOrganisingConcept: spec.centralOrganisingConcept,
      prevalence,
      tone: toneOf(tone.pos, tone.neg),
      codes: codesByTheme.get(spec.id) ?? [],
      bySegment: segmentBreakdown(spec.id),
      illustrativeExtracts: extractsFor(themeExtracts.get(spec.id) ?? [], prevalence),
      thin: prevalence > 0 && prevalence < MIN_PREVALENCE_FOR_THEME,
    };
  })
    .filter((t) => t.prevalence > 0)
    .sort((a, b) => b.prevalence - a.prevalence || a.id.localeCompare(b.id));

  // ── Phases 4–5: apply the consultant review ──
  const reviewedThemes = applyReview({
    candidateIds: new Set(candidateThemes.map((t) => t.id)),
    review: opts.review ?? {},
    specById,
    themeComments,
    themeSegmentComments,
    themeTone,
    themeExtracts,
    codesByTheme,
    extractsFor,
  });

  return { familiarisation, codes, candidateThemes, reviewedThemes };
}

// ── Review application (deterministic; keep / merge / discard / name+define) ───

interface ReviewCtx {
  candidateIds: Set<string>;
  review: ThemeReview;
  specById: Map<string, CandidateThemeSpec>;
  themeComments: Map<string, Set<number>>;
  themeSegmentComments: Map<string, Map<string, Set<number>>>;
  themeTone: Map<string, { pos: number; neg: number }>;
  themeExtracts: Map<string, { text: string; len: number }[]>;
  codesByTheme: Map<string, CodeResult[]>;
  extractsFor: (c: { text: string; len: number }[], prevalence: number) => string[];
}

function applyReview(ctx: ReviewCtx): ReviewedTheme[] {
  const decisionOf = (id: string): ThemeDecision => ctx.review[id]?.decision ?? "unreviewed";
  const isDiscarded = (id: string) => decisionOf(id) === "discard";

  // Resolve a merge chain to its final surviving target (guards against cycles
  // and merges pointing at missing/discarded themes — those merges are ignored).
  const resolveTarget = (id: string, seen = new Set<string>()): string | null => {
    const e = ctx.review[id];
    if (!e || e.decision !== "merge" || !e.mergedInto) return null;
    const target = e.mergedInto;
    if (!ctx.candidateIds.has(target) || isDiscarded(target) || seen.has(id)) return null;
    seen.add(id);
    return resolveTarget(target, seen) ?? target;
  };

  // Group each surviving candidate under its output theme (itself, or its target).
  const membersOf = new Map<string, string[]>();
  for (const id of ctx.candidateIds) {
    if (isDiscarded(id)) continue;
    const target = resolveTarget(id);
    if (target) {
      if (!membersOf.has(target)) membersOf.set(target, [target]);
      const arr = membersOf.get(target)!;
      if (!arr.includes(id)) arr.push(id);
    } else if (!membersOf.has(id)) {
      membersOf.set(id, [id]);
    }
  }

  const out: ReviewedTheme[] = [];
  for (const [outId, memberIds] of membersOf) {
    const spec = ctx.specById.get(outId)!;
    const entry = ctx.review[outId];
    const commentUnion = new Set<number>();
    const segUnion = new Map<string, Set<number>>();
    let pos = 0;
    let neg = 0;
    const codeList: CodeResult[] = [];
    const extractCands: { text: string; len: number }[] = [];
    const mergedFrom: string[] = [];

    for (const mId of memberIds) {
      for (const i of ctx.themeComments.get(mId) ?? []) commentUnion.add(i);
      for (const [seg, set] of ctx.themeSegmentComments.get(mId) ?? new Map()) {
        if (!segUnion.has(seg)) segUnion.set(seg, new Set());
        for (const i of set) segUnion.get(seg)!.add(i);
      }
      const tt = ctx.themeTone.get(mId);
      if (tt) {
        pos += tt.pos;
        neg += tt.neg;
      }
      codeList.push(...(ctx.codesByTheme.get(mId) ?? []));
      extractCands.push(...(ctx.themeExtracts.get(mId) ?? []));
      if (mId !== outId) mergedFrom.push(ctx.specById.get(mId)?.provisionalName ?? mId);
    }

    const prevalence = commentUnion.size;
    const named = !!entry?.name?.trim();
    out.push({
      id: outId,
      name: entry?.name?.trim() || spec.provisionalName,
      definition: entry?.definition?.trim() || spec.centralOrganisingConcept,
      status: entry?.decision === "keep" || named ? "confirmed" : "candidate",
      reviewed: (entry?.decision ?? "unreviewed") !== "unreviewed",
      prevalence,
      tone: toneOf(pos, neg),
      codes: codeList.sort((a, b) => b.count - a.count || a.id.localeCompare(b.id)),
      bySegment: [...segUnion]
        .map(([segment, set]) => ({ segment, count: set.size }))
        .sort((a, b) => b.count - a.count || a.segment.localeCompare(b.segment)),
      illustrativeExtracts: ctx.extractsFor(extractCands, prevalence),
      thin: prevalence > 0 && prevalence < MIN_PREVALENCE_FOR_THEME,
      mergedFrom: mergedFrom.sort(),
      ...(entry?.note?.trim() ? { note: entry.note.trim() } : {}),
    });
  }

  return out.sort((a, b) => b.prevalence - a.prevalence || a.id.localeCompare(b.id));
}

/**
 * THEMATIC ANALYSIS ENGINE (Method A — reflexive TA, deterministic first pass).
 *
 * Structures open-text analysis around Braun & Clarke's *reflexive thematic
 * analysis* (Thematic Analysis: A Practical Guide, SAGE, 2022) — but honestly.
 * A deterministic system can only do the mechanical, first-pass portion of the
 * six phases; the interpretive work is explicitly left to a human analyst:
 *
 *   Phase 1  Familiarisation      → machine: dataset descriptives (this file)
 *   Phase 2  Coding               → machine: transparent codebook, SEMANTIC only
 *   Phase 3  Generating themes     → machine: collate codes into CANDIDATE themes
 *   Phase 4  Reviewing themes       → CONSULTANT (reflexive; not in this file)
 *   Phase 5  Defining & naming      → CONSULTANT (reflexive; not in this file)
 *   Phase 6  Writing up             → report (renders both layers, labelled)
 *
 * Braun & Clarke are emphatic that themes are actively GENERATED by a reflexive
 * analyst, never mechanically "extracted" or "emergent". So everything this
 * engine produces is labelled a CANDIDATE — a starting point for the consultant,
 * not a finished interpretation. Coding here is deductive against the platform's
 * 5C framework plus an explicit "uncoded" bucket that flags material the codebook
 * did not catch and a human must read. No LLM. No latent/interpretative claims.
 *
 * Privacy: every extract passes through redactOpenText, and extracts are gated on
 * BOTH dataset size and per-theme prevalence so no small-N verbatim can surface.
 */

import { OPEN_TEXT_QUESTIONS, redactOpenText } from "@/lib/openText";

export interface OpenTextEntry {
  text: string;
  segment: string | null;
  questionId?: number;
}

/** A code in the codebook: a small, semantic-level analytic label. */
interface CodebookCode {
  id: string;
  label: string;
  /** What this code captures — surfaced in the report so coding is auditable. */
  definition: string;
  /** Inclusion terms (lowercased). Single alphabetic words match on word
   *  boundaries; anything with a space/punctuation matches as a substring. */
  keywords: string[];
  candidateThemeId: string;
}

/** A candidate theme: a central organising concept several codes point to. */
interface CandidateThemeSpec {
  id: string;
  /** Provisional name — the consultant renames in Phase 5. */
  provisionalName: string;
  centralOrganisingConcept: string;
}

